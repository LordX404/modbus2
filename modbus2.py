def get_system_info(client, unit=1):
    try:
        result = client.read_holding_registers(40, 8, unit=unit)
        if result.isError():
            print(f"O dispositivo na unidade {unit} não suporta System Info via Modbus.")
            return None
        regs = result.registers
        uptime = regs_u32(regs[0:2])
        memory_total = regs_u32(regs[2:4])
        memory_free = regs_u32(regs[4:6])
        cpu_load = regs[6]
        temperature = regs[7] / 10.0
        table = PrettyTable()
        table.field_names = ["Parametro", "Valor"]
        table.add_row(["Uptime (s)", uptime])
        table.add_row(["Memory Total (B)", memory_total])
        table.add_row(["Memory Free (B)", memory_free])
        table.add_row(["CPU Load (%)", cpu_load])
        table.add_row(["Temperature (°C)", temperature])
        print(table)
        return {
            "uptime": uptime,
            "memory_total": memory_total,
            "memory_free": memory_free,
            "cpu_load": cpu_load,
            "temperature": temperature
        }
    except Exception as e:
        print(f"O dispositivo na unidade {unit} não fornece System Info ou ocorreu erro: {e}")
        return None

def read_coils(client, addr, count, unit=1):
    try:
        r = client.read_coils(addr, count, unit=unit)
        if r.isError(): return r
        return r.bits
    except Exception as e:
        print(f"Erro ao ler coils: {e}")
        return None

def read_hregs(client, addr, count, unit=1):
    try:
        r = client.read_holding_registers(addr, count, unit=unit)
        if r.isError(): return r
        return r.registers
    except Exception as e:
        print(f"Erro ao ler registradores: {e}")
        return None

def write_coil(client, addr, value, unit=1):
    try:
        r = client.write_coil(addr, int(value), unit=unit)
        return r
    except Exception as e:
        print(f"Erro ao escrever coil: {e}")
        return None

def write_regs(client, addr, values, unit=1):
    try:
        values = [int(v) for v in values]
        r = client.write_registers(addr, values, unit=unit)
        return r
    except Exception as e:
        print(f"Erro ao escrever registradores: {e}")
        return None

def send_payload(client, addr, payload, unit=1):
    try:
        r = client.write_registers(addr, payload, unit=unit)
        return r
    except Exception as e:
        print(f"Erro ao enviar payload: {e}")
        return None


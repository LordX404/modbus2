def main():
    ip = input("Digite o IP do dispositivo/SCADA: ").strip()
    clients = {}  
    try:
        print("Escaneando slaves Modbus no dispositivo... isso pode demorar alguns segundos...")
        slaves = scan_slaves(ip)
        if not slaves:
            print("Nenhum slave Modbus encontrado, tentando conectar ao dispositivo...")
        if not slaves:
            client = connect_modbus(ip)
            clients = {0: client}
        else:
            clients = {s: connect_modbus(ip, unit=s) for s in slaves}

        global running
        running = True
        history = []
        macros = {}

        while running:
            try:
                line = input(">> ")
                exec_cmd(clients, line, macros, history)
            except KeyboardInterrupt:
                print("\nInterrompido pelo usuário.")
                break
    except Exception as e:
        print("Erro:", e)
    finally:
        for c in clients.values():
            c.close()

if __name__ == "__main__":
    main()

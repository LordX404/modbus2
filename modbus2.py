connected_devices = {}

def u16(v): return int(v) & 0xFFFF
def b(v): return bool(int(v))
def regs_u32(r): return (r[0] << 16) | r[1]
def regs_i32(r): return struct.unpack(">i", struct.pack(">I", regs_u32(r)))[0]
def regs_f32(r): return struct.unpack(">f", struct.pack(">I", regs_u32(r)))[0]
def u32_regs(v): return [(v >> 16) & 0xFFFF, v & 0xFFFF]
def f32_regs(v): return list(struct.unpack(">HH", struct.pack(">f", float(v))))

def scan_slaves(ip, port=502, start=1, end=247, timeout=0.1):
    found = []
    for s in range(start, end + 1):
        try:
            client = ModbusTcpClient(ip, port=port, timeout=timeout)
            r = client.read_coils(0, 1, unit=s)
            if r and not r.isError():
                found.append(s)
            client.close()
        except:
            pass
    return found

def connect_modbus(ip, port=502, unit=None):
    client = ModbusTcpClient(ip, port=port, timeout=3)
    retries = 3
    while retries > 0:
        if client.connect():
            return client
        retries -= 1
        time.sleep(random.uniform(0.1, 1))
    raise Exception("Falha ao conectar com o dispositivo após múltiplas tentativas.")

